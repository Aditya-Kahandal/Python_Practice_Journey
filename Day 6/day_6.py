# Reversing a String

def strReverse(word):
    result= ""
    for e in word:
        result = e + result
    return result

word = "python"
print(strReverse(word))

# Check Palindrome String

def checkPalindrome(str1):
    left = 0
    right = len(str1) - left - 1

    while left < (len(str1)//2)+ 1:
        if str1[left] != str1[right]:
            return False
        left += 1
        right -= 1

    return True

word = "madam"
print(checkPalindrome(word))

