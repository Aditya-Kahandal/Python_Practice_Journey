# First Unique Character

def firstUnique(word):
    freq = {}
    for char in word:
        if char in freq:
            freq[char] += 1
        else:
            freq[char] = 1

    for e in freq:
        if freq[e] == 1:
            return e

    return -1

word = "swiss"
print(firstUnique(word))