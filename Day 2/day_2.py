# 3. Function to count number of vowels in a string

def vowelCounter(str1):
  if str1 == "":
    return 0
  lower_str = str1.lower() # to make sure there is no logic error in cases of string
  count = 0
  for i in range(0, len(lower_str)):
    if (lower_str[i] == "a" or lower_str[i] =="e" or lower_str[i] =="i" or lower_str[i] == "o" or lower_str[i] =="u"):
      count = count + 1
    else:
      continue
  return count

msg = input("Enter a string: ")
print("Number of Vowels in \"",msg,"\"is:",vowelCounter(msg))

