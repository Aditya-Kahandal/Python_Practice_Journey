# Problem 2: Largest element in list

def LargestElement(arr):
  if(len(arr) == 0):
    return -1
  largest = arr[0]
  for i in range (0, len(arr)):
    if arr[i] > largest:
      largest = arr[i]
  return largest

array1 = [3,15,62,23,101,90]

print(LargestElement(array1))

